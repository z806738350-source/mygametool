import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { createApp } from "../src/daemon/app.js";
import { AgentRuntimeService } from "../src/daemon/agent-runtimes/service.js";
import { CODEX_IMAGE_MODEL } from "../src/daemon/agent-runtimes/codex-image-provider.js";
import { createAssetGenerationNode } from "../src/shared/asset-canvas.js";
import type { ImageModelCatalog, ProjectState, ProviderSummary, ToolJob } from "../src/shared/contracts.js";
import type { CanvasBoardDetail, CanvasWorkspaceDetail } from "../src/shared/canvas-workspace.js";

const cleanup: Array<() => Promise<unknown>> = [];
afterEach(async () => { for (const close of cleanup.splice(0).reverse()) await close(); vi.restoreAllMocks(); });

it("preserves canvas references but refuses the retired Codex image provider before CLI discovery or generation", async () => {
  const directory = await mkdtemp(path.join(tmpdir(), "ohmygame-codex-canvas-retired-"));
  cleanup.push(() => rm(directory, { recursive: true, force: true }));
  await writeFile(path.join(directory, "agent-runtimes.json"), JSON.stringify({ runtimes: { "codex-cli": { binaryPath: path.join(directory, "unavailable-codex"), enabled: true } } }));
  const connect = vi.spyOn(AgentRuntimeService.prototype, "codexImageConnection").mockRejectedValue(new Error("Retired CLI must not be discovered"));
  const request = vi.fn<typeof fetch>().mockRejectedValue(new Error("No model request is permitted"));
  let app = createApp({ dataDirectory: directory, piAgentDirectory: path.join(directory, "pi"), imageFetch: request });
  cleanup.push(() => app.close());
  const call = (method: "GET" | "POST" | "PUT" | "PATCH", url: string, payload?: object) => app.inject({ method, url, ...(payload ? { payload } : {}) });
  const ref = { provider: "codex-cli", id: "codex-image" };
  expect((await call("GET", "/image-models/catalog")).json<ImageModelCatalog>().models).not.toContainEqual(CODEX_IMAGE_MODEL);
  expect((await call("GET", "/settings/providers")).json<ProviderSummary[]>().some((provider) => provider.id === "codex-cli")).toBe(false);
  expect((await call("PUT", "/image-models/default", ref)).statusCode).toBe(400);
  const project = (await call("POST", "/projects", { name: "Codex canvas", type: "asset-canvas" })).json<ProjectState>();
  const base = `/projects/${project.id}/canvas`;
  const workspace = (await call("GET", `${base}/workspace`)).json<CanvasWorkspaceDetail>();
  const boardUrl = `${base}/boards/${workspace.boards[0]!.id}`;
  const board = (await call("GET", boardUrl)).json<CanvasBoardDetail>();
  const png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=";
  const references = await Promise.all(["content", "style"].map(async (name) => {
    const uploaded = await call("POST", "/library/assets", { name, purpose: "reference", image: { data: png, mediaType: "image/png" } });
    expect(uploaded.statusCode, uploaded.body).toBe(201);
    return { type: "library" as const, assetId: uploaded.json<{ id: string }>().id };
  }));
  const node = createAssetGenerationNode("image", { x: 0, y: 0 }, { imageModel: ref });
  if (node.type !== "image") throw new Error("Expected image node");
  node.data.prompt = "An orange cat"; node.data.images = references;
  board.board.nodes.push(node); board.board.editorLayout.nodes[node.id] = node.position;
  expect((await call("PUT", boardUrl, board)).statusCode).toBe(200);
  const generated = await call("POST", `${boardUrl}/nodes/${node.id}/generate`);
  expect(generated.statusCode, generated.body).toBe(202);
  await expect.poll(async () => (await call("GET", `${base}/jobs`)).json<ToolJob[]>()[0]?.status).toBe("failed");
  const failed = (await call("GET", `${base}/jobs`)).json<ToolJob[]>()[0]!;
  expect(failed.model).toEqual(ref); expect(failed.error).toContain("The selected image model is unavailable");
  const saved = (await call("GET", boardUrl)).json<CanvasBoardDetail>().board.nodes.find((item) => item.id === node.id)!;
  if (saved.type !== "image") throw new Error("Expected image node");
  expect(saved.data.images).toEqual(references); expect(saved.data.assetId).toBeUndefined();
  expect((await call("GET", "/library/assets")).json()).toHaveLength(2);
  await app.close();
  app = createApp({ dataDirectory: directory, piAgentDirectory: path.join(directory, "pi"), imageFetch: request });
  const enabled = await call("PATCH", "/settings/models/providers/codex-cli/enabled", { enabled: true });
  expect(enabled.statusCode).toBe(404);
  const rechecked = await call("POST", "/settings/models/providers/codex-cli/images/recheck");
  expect(rechecked.json()).toMatchObject({ configured: false, enabled: false, error: expect.stringContaining("isolated execution") });
  expect((await call("GET", "/image-models/catalog")).json<ImageModelCatalog>().models.some((model) => model.provider === "codex-cli")).toBe(false);
  expect(connect).not.toHaveBeenCalled(); expect(request).not.toHaveBeenCalled();
});
